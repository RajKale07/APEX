import { useState } from "react";

interface Props {
  ir: string;
}

export default function IRViewer({ ir }: Props) {
  const [open, setOpen]     = useState(false);
  const [copied, setCopied] = useState(false);

  const copyIR = (e: React.MouseEvent) => {
    e.stopPropagation();
    navigator.clipboard.writeText(ir);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const lineCount = ir.split("\n").length;

  return (
    <div className="card">
      <div className="card-header" onClick={() => setOpen(o => !o)} style={{ cursor: "pointer" }}>
        <div className="header-title-group">
          <span className="card-title">LLVM Intermediate Representation (.ll)</span>
          <span className="badge">{lineCount} lines</span>
        </div>
        <div className="header-actions">
          <button className="small-btn" onClick={copyIR}>
            {copied ? "Copied" : "Copy IR"}
          </button>
          <button className="small-btn" onClick={() => setOpen(o => !o)}>
            {open ? "▲ Collapse" : "▼ Expand"}
          </button>
        </div>
      </div>

      <div className="card-body">
        {!open ? (
          <div className="ir-hint" onClick={() => setOpen(true)}>
            Raw unoptimized LLVM IR generated by Clang — click expand to view parsed assembly.
          </div>
        ) : (
          <div className="ir-view">
            <pre className="ir-code">{ir}</pre>
          </div>
        )}
      </div>
    </div>
  );
}
